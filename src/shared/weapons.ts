export interface HitCalculationInput {
  weapon: WeaponSpec;
  distanceMeters: number;
  hitGroup: 'head' | 'chest' | 'stomach' | 'leg';
  targetArmor: number;
  targetHasHelmet: boolean;
  wallPenetrationLoss?: number; // 0 to 0.9
}

export interface HitCalculationResult {
  healthDamage: number;
  armorDamage: number;
  isFatal: boolean;
}

export function calculateWeaponDamage(
  input: HitCalculationInput,
  currentTargetHealth = 100
): HitCalculationResult {
  const { weapon, distanceMeters, hitGroup, targetArmor, targetHasHelmet, wallPenetrationLoss = 0 } = input;

  // Distance falloff per 15 meters
  const falloffSegments = Math.max(0, distanceMeters / 15);
  const distanceFactor = Math.pow(weapon.rangeModifier, falloffSegments);

  // Hitbox multiplier
  let groupMult = weapon.chestMultiplier;
  if (hitGroup === 'head') groupMult = weapon.headMultiplier;
  else if (hitGroup === 'stomach') groupMult = weapon.stomachMultiplier;
  else if (hitGroup === 'leg') groupMult = weapon.legMultiplier;

  // Wallbang reduction
  const penetrationFactor = Math.max(0.1, 1 - wallPenetrationLoss);

  let rawDamage = weapon.damage * distanceFactor * groupMult * penetrationFactor;

  // Armor calculation (legs are unarmored; head requires helmet)
  const isArmoredHit =
    targetArmor > 0 &&
    hitGroup !== 'leg' &&
    (hitGroup !== 'head' || targetHasHelmet);

  let armorDamage = 0;
  if (isArmoredHit) {
    const absorbedByArmor = rawDamage * (1 - weapon.armorPenetration) * 0.5;
    armorDamage = Math.min(targetArmor, Math.ceil(absorbedByArmor));
    rawDamage = rawDamage * weapon.armorPenetration;
  }

  const healthDamage = Math.max(1, Math.round(rawDamage));
  return {
    healthDamage,
    armorDamage,
    isFatal: healthDamage >= currentTargetHealth
  };
}

export function getWeaponsByCategory(category: WeaponCategory, team?: 'SENTINEL' | 'VORTEX'): WeaponSpec[] {
  return Object.values(WEAPON_SPECS).filter(
    (w) => w.category === category && (!team || w.team === 'BOTH' || w.team === team)
  );
}
