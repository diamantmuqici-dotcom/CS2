function generateSprayPattern(
  shots: number,
  verticalClimb: number,
  horizontalSway: number,
  seed: number
): Array<[number, number]> {
  const pattern: Array<[number, number]> = [];
  for (let i = 0; i < shots; i++) {
    const progress = i / Math.max(1, shots - 1);
    // Initial vertical climb, then horizontal T/S curve like classic tactical rifles
    const pitch =
      i < 8
        ? verticalClimb * (0.85 + i * 0.06)
        : i < 16
        ? verticalClimb * 0.45
        : verticalClimb * 0.15;
    const phase = Math.sin((i - 5) * 0.45 + seed);
    const yaw = i < 4 ? horizontalSway * 0.15 * (i % 2 === 0 ? 1 : -1) : horizontalSway * phase * (0.6 + progress * 0.5);
    pattern.push([Number(pitch.toFixed(4)), Number(yaw.toFixed(4))]);
  }
  return pattern;
}

